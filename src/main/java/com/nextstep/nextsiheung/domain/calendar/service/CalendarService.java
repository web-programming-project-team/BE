package com.nextstep.nextsiheung.domain.calendar.service;

import com.nextstep.nextsiheung.domain.calendar.dto.CalendarEventCreateRequest;
import com.nextstep.nextsiheung.domain.calendar.dto.CalendarEventResponse;
import com.nextstep.nextsiheung.domain.calendar.dto.EventIdResponse;
import com.nextstep.nextsiheung.domain.calendar.entity.CalendarEvent;
import com.nextstep.nextsiheung.domain.calendar.repository.CalendarEventRepository;
import com.nextstep.nextsiheung.domain.policy.entity.Policy;
import com.nextstep.nextsiheung.domain.policy.repository.PolicyRepository;
import com.nextstep.nextsiheung.domain.roadmap.entity.RoadmapItem;
import com.nextstep.nextsiheung.domain.user.entity.User;
import com.nextstep.nextsiheung.domain.user.repository.UserRepository;
import com.nextstep.nextsiheung.global.common.Kst;
import com.nextstep.nextsiheung.global.common.enums.EventType;
import com.nextstep.nextsiheung.global.exception.BusinessException;
import com.nextstep.nextsiheung.global.exception.ErrorCode;
import java.time.LocalDate;
import java.time.YearMonth;
import java.util.ArrayList;
import java.util.List;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

// NEXT 캘린더: 월별·다가오는 일정 조회, 직접 추가·삭제, 로드맵 항목의 자동 일정 생성
@Service
@RequiredArgsConstructor
public class CalendarService {

    private static final int UPCOMING_MAX_DAYS = 30;

    private final CalendarEventRepository eventRepository;
    private final PolicyRepository policyRepository;
    private final UserRepository userRepository;

    @Transactional(readOnly = true)
    public List<CalendarEventResponse> monthly(Long userId, int year, int month, List<EventType> types) {
        if (month < 1 || month > 12) {
            throw new BusinessException(ErrorCode.INVALID_INPUT);
        }
        YearMonth ym = YearMonth.of(year, month);
        return find(userId, ym.atDay(1), ym.atEndOfMonth(), types);
    }

    // 캘린더 오른쪽 패널 '이번 주 마감'. days는 기본 7, 최대 30
    @Transactional(readOnly = true)
    public List<CalendarEventResponse> upcoming(Long userId, int days) {
        if (days < 1 || days > UPCOMING_MAX_DAYS) {
            throw new BusinessException(ErrorCode.INVALID_INPUT);
        }
        LocalDate today = Kst.today();
        return find(userId, today, today.plusDays(days), null);
    }

    // policyId가 있으면 그 정책의 상담일·참여일 같은 일정, 없으면 title·date로 CUSTOM 일정
    @Transactional
    public EventIdResponse create(Long userId, CalendarEventCreateRequest request) {
        User user = userRepository.getReferenceById(userId);
        CalendarEvent event;
        if (request.policyId() != null) {
            Policy policy = policyRepository.findById(request.policyId())
                    .orElseThrow(() -> new BusinessException(ErrorCode.POLICY_NOT_FOUND));
            String title = isBlank(request.title()) ? policy.getTitle() : request.title().trim();
            event = CalendarEvent.forPolicy(user, policy, request.type(), request.date(), request.eventTime(), title,
                    request.memo());
        } else {
            if (isBlank(request.title())) {
                throw new BusinessException(ErrorCode.INVALID_INPUT);
            }
            event = CalendarEvent.custom(user, request.date(), request.eventTime(), request.title().trim(),
                    request.memo());
        }
        return new EventIdResponse(eventRepository.save(event).getId());
    }

    // 직접 추가한 일정만 지운다. 자동 일정은 로드맵 항목이나 관심 공고를 지우면 함께 사라진다
    @Transactional
    public void delete(Long userId, Long eventId) {
        CalendarEvent event = eventRepository.findById(eventId)
                .orElseThrow(() -> new BusinessException(ErrorCode.EVENT_NOT_FOUND));
        if (!event.getUser().getId().equals(userId) || event.isAutoGenerated()) {
            throw new BusinessException(ErrorCode.FORBIDDEN);
        }
        eventRepository.delete(event);
    }

    // 로드맵 항목이 생기면 정책의 접수 시작·마감일을 일정으로 넣는다 (날짜가 없으면 건너뜀)
    @Transactional
    public List<Long> addRoadmapItemEvents(User user, RoadmapItem item) {
        Policy policy = item.getPolicy();
        List<CalendarEvent> events = new ArrayList<>();
        if (policy.getApplyStartDate() != null) {
            events.add(CalendarEvent.forRoadmapItem(user, item, EventType.APPLY_START, policy.getApplyStartDate(),
                    policy.getTitle() + " 접수 시작"));
        }
        if (policy.getApplyEndDate() != null) {
            events.add(CalendarEvent.forRoadmapItem(user, item, EventType.APPLY_END, policy.getApplyEndDate(),
                    policy.getTitle() + " 접수 마감"));
        }
        return eventRepository.saveAll(events).stream().map(CalendarEvent::getId).toList();
    }

    @Transactional
    public void removeRoadmapEvents(Long roadmapId) {
        eventRepository.deleteByRoadmapId(roadmapId);
    }

    private List<CalendarEventResponse> find(Long userId, LocalDate from, LocalDate to, List<EventType> types) {
        List<CalendarEvent> events = types == null || types.isEmpty()
                ? eventRepository.findInRange(userId, from, to)
                : eventRepository.findInRange(userId, from, to, types);
        return events.stream().map(CalendarService::toResponse).toList();
    }

    private static CalendarEventResponse toResponse(CalendarEvent e) {
        return new CalendarEventResponse(e.getId(), e.getDate(), e.getEventTime(), e.getType(), e.getTitle(),
                e.getSourceType(), e.sourceId(), e.getItem() == null ? null : e.getItem().getStatus(),
                Kst.dDay(e.getDate()));
    }

    private static boolean isBlank(String s) {
        return s == null || s.isBlank();
    }
}
